#!/usr/bin/env python3
"""
Generates the requirements traceability matrix docs/22-traceability-matrix.md.

Requirements come from the URS tables in docs/08-urs.md. A test names a requirement in one of three ways:
  * C#:  [Trait("Req", "URS-XXX-nnn")] on a test class (all its tests) or a test method;
  * Angular specs (web/src/**/*.spec.ts) and end-to-end suites (web/e2e/*.cjs): the ID in a comment or test name.
The matrix lists, per requirement, the tests that name it. It says nothing about whether those tests are enough; that is a QA
judgement (doc 11). It does show which requirements no test names at all.

  python3 tools/rtm_gen.py            write docs/22-traceability-matrix.md
  python3 tools/rtm_gen.py --check    exit 1 if the file is out of date or a test names an unknown requirement
"""
from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
URS = ROOT / "docs" / "08-urs.md"
OUT = ROOT / "docs" / "22-traceability-matrix.md"

ID = re.compile(r"\bURS-[A-Z]+-\d{3}\b")
ROW = re.compile(r"^\| (URS-[A-Z]+-\d{3}) \| (.+?) \| ([MHD]) \| ([YN]) \| ([HML]) \|\s*$")
SECTION = re.compile(r"^## (\d+\.\d+) (.+)$")
TRAIT = re.compile(r'\[Trait\("Req",\s*"([^"]+)"\)\]')
CLASS = re.compile(r"^\s*(?:public |internal )?(?:sealed |static |abstract )*(?:partial )?class (\w+)")
METHOD = re.compile(r"^\s*public (?:async )?(?:Task|void) (\w+)\(")
TEST_ATTR = re.compile(r"^\s*\[(?:Fact|Theory)\b")


def read_urs():
    sections, rows, current = [], {}, None
    for line in URS.read_text(encoding="utf-8").splitlines():
        if m := SECTION.match(line):
            current = (m.group(1), m.group(2))
            sections.append(current)
        elif m := ROW.match(line):
            rows[m.group(1)] = {"text": m.group(2), "pri": m.group(3), "gxp": m.group(4), "risk": m.group(5), "section": current}
    return sections, rows


def scan_csharp():
    """-> {requirement: set of 'Class (n tests)' / 'Class.Method'}"""
    found = defaultdict(set)
    for path in sorted((ROOT / "tests").rglob("*.cs")):
        if "/obj/" in path.as_posix() or "/bin/" in path.as_posix():
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        classes = []  # [name, class_traits, [(method, traits)]]
        pending, in_test = [], False
        for line in lines:
            if m := TRAIT.search(line):
                pending.append(m.group(1))
                continue
            if m := CLASS.match(line):
                classes.append([m.group(1), pending, []])
                pending, in_test = [], False
                continue
            if TEST_ATTR.match(line):
                in_test = True
                continue
            if (m := METHOD.match(line)) and in_test and classes:
                classes[-1][2].append((m.group(1), pending))
                pending, in_test = [], False
        for name, class_traits, methods in classes:
            for req in class_traits:
                found[req].add(f"{name} ({len(methods)} tests)")
            for method, traits in methods:
                for req in traits:
                    if req not in class_traits:
                        found[req].add(f"{name}.{method}")
    return found


def scan_text_files():
    """Angular specs and end-to-end suites: file-level references."""
    found = defaultdict(set)
    paths = sorted((ROOT / "web" / "src").rglob("*.spec.ts")) + sorted((ROOT / "web" / "e2e").glob("*.cjs"))
    for path in paths:
        for req in set(ID.findall(path.read_text(encoding="utf-8"))):
            found[req].add(path.relative_to(ROOT).as_posix())
    return found


def render(sections, rows, coverage):
    total = len(rows)
    covered = [r for r in rows if coverage.get(r)]
    mandatory = [r for r, v in rows.items() if v["pri"] == "M"]
    mandatory_covered = [r for r in mandatory if coverage.get(r)]
    out = [
        "# 22. Requirements Traceability Matrix",
        "",
        "> Generated by `tools/rtm_gen.py` from `docs/08-urs.md` and the tests. Do not edit by hand; CI fails when it is out of date.",
        "",
        "A test is listed when it names the requirement (C#: `[Trait(\"Req\", …)]`; Angular specs and end-to-end suites: the ID in a",
        "comment). **Listing a test does not mean it is enough.** Whether the tests demonstrate a requirement fully, partly or not at all",
        "is a QA judgement made when the test scripts are reviewed (doc 11). An empty row means no test names the requirement, which",
        "is also the case for requirements the platform does not implement yet.",
        "",
        "Interim: doc 11 plans the product RTM to be generated from `val.trace_link`; until the validation module exists, this file is",
        "generated from the tests instead.",
        "",
        "| | Requirements | With at least one test |",
        "|---|---|---|",
        f"| All | {total} | {len(covered)} |",
        f"| Mandatory (M) | {len(mandatory)} | {len(mandatory_covered)} |",
        "",
    ]
    for number, title in sections:
        ids = [r for r, v in rows.items() if v["section"] == (number, title)]
        if not ids:
            continue
        out += [f"## {number} {title}", "", "| ID | Requirement | Pri · GxP · Risk | Tests naming it |", "|---|---|---|---|"]
        for r in ids:
            v = rows[r]
            tests = "<br>".join(f"`{t}`" for t in sorted(coverage.get(r, []))) or "—"
            out.append(f"| {r} | {v['text']} | {v['pri']} · {v['gxp']} · {v['risk']} | {tests} |")
        out.append("")
    gaps = [r for r in mandatory if not coverage.get(r)]
    out += ["## Mandatory requirements that no test names", ""]
    if gaps:
        out += [f"{len(gaps)} of {len(mandatory)}:", ""]
        out += [f"- {r}: {rows[r]['text']}" for r in gaps]
    else:
        out.append("None.")
    out.append("")
    return "\n".join(out)


def main():
    sections, rows = read_urs()
    coverage = defaultdict(set)
    for source in (scan_csharp(), scan_text_files()):
        for req, tests in source.items():
            coverage[req] |= tests
    unknown = sorted(r for r in coverage if r.startswith("URS-") and r not in rows)
    text = render(sections, rows, coverage)
    if "--check" in sys.argv:
        problems = []
        if unknown:
            problems.append("tests name requirements that are not in the URS: " + ", ".join(unknown))
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            problems.append(f"{OUT.relative_to(ROOT)} is out of date; run python3 tools/rtm_gen.py")
        for p in problems:
            print(f"rtm_gen: {p}", file=sys.stderr)
        sys.exit(1 if problems else 0)
    if unknown:
        print("rtm_gen: warning: tests name requirements that are not in the URS: " + ", ".join(unknown), file=sys.stderr)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} requirements")


if __name__ == "__main__":
    main()
